#!/usr/bin/env python
"""App and dataset figures quoted in the slides and report; writes reports/app_numbers.md.

Recomputes everything from the stored tables and prediction files, so each figure is backed
by a file. Reads no BRIGHTER text and uses no GPU.
"""
from __future__ import annotations

import re
import statistics as st
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from emoldgn.evaluate import cooccurrence_fidelity, track_a, track_b  # noqa: E402
from eval.app_eval import aspect_gold_check, valence_check  # noqa: E402
from spark_jobs.common import load_config  # noqa: E402


def data_lines() -> list[str]:
    """Dataset totals and label medians, from reports/DATA_NOTES.md."""
    L = (ROOT / "reports/DATA_NOTES.md").read_text(encoding="utf-8").split("\n")
    rows = [[c.strip() for c in x.split("|")[1:-1]] for x in L if re.match(r"\| [a-z]{3,4} \| [a-z]+ \| A \|", x)]
    train, dev, test, inten = (sum(int(r[i]) for r in rows) for i in (3, 4, 5, 7))
    out = ["## Dataset", "", f"- Track A rows: {train + dev + test:,} (train {train:,}, dev {dev:,}, test {test:,})",
           f"- Intensity rows: {inten:,}", ""]
    s = [k for k, x in enumerate(L) if x.startswith("## Label prevalence")][0]
    prev = [[c.strip() for c in x.split("|")[1:-1]] for x in L[s + 4:s + 32]]
    for i, name in enumerate("anger disgust fear joy sadness surprise neutral".split(), 1):
        v = [float(r[i]) for r in prev if r[i] not in ("-", "")]
        out.append(f"- {name}: median {st.median(v):.3f}, lowest {min(v):.3f}, highest {max(v):.3f}")
    return out


def app_lines(profile: str) -> list[str]:
    """Clause and document rates for one application, from the current tables."""
    g = ROOT / "apps/gold" / profile
    c = pd.read_parquet(g / "clauses", columns=["present", "lang"])
    d = pd.read_parquet(g / "documents", columns=["escalate"])
    p = np.stack(c["present"].map(np.asarray).values)  # one 0/1 column per emotion, in EMOS order
    fear = pd.Series(p[:, 2] > 0)
    neg = pd.Series((p[:, 0] > 0) | (p[:, 4] > 0))
    return [f"## {profile}", "", f"- Clauses: {len(c):,}; documents: {len(d):,}", f"- Fear flagged: {100 * fear.mean():.1f}% of clauses",
            f"- P(fear | anger or sadness): {100 * fear[neg].mean():.1f}%", f"- Escalated: {int(d['escalate'].sum()):,} documents ({100 * d['escalate'].mean():.1f}%)", ""]


def english_lines() -> list[str]:
    """English validation, the two models considered for the applications."""
    out = ["## English validation", "", "| Model | Macro-F1 | Pearson | Anger Pearson |", "|---|---|---|---|"]
    for e in ("final_full_noquota", "best_full"):
        d = np.load(ROOT / "runs" / e / "predictions/val.npz", allow_pickle=True)
        m = d["lang"] == "eng"
        a = track_a(d["y"][m], d["pred"][m], d["mask"][m], d["lang"][m])["mean"]
        t = track_b(d["intensity"][m], d["int_pred"][m], d["lang"][m])
        out.append(f"| {e} | {100 * a:.2f} | {t['mean']:.3f} | {t['per_emotion']['eng']['anger']:.3f} |")
    return out + [""]


def main() -> None:
    cfg = load_config()
    L = ["# Figures for the slides and report", "", "Generated by scripts/app_numbers.py from stored tables and predictions.", ""]
    L += data_lines() + [""] + app_lines("customer_support") + app_lines("student_feedback") + english_lines()
    L += ["## Checks against EduRABSA gold labels", "", f"- Valence: {valence_check(cfg)}", f"- Aspects: {aspect_gold_check(cfg)}", ""]
    (ROOT / "reports/app_numbers.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
