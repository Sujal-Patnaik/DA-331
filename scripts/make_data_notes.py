#!/usr/bin/env python
"""M1 report: reports/DATA_NOTES.md, with counts only (no BRIGHTER text, rule 7)."""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from spark_jobs.common import EMOS, families, load_config, path_of  # noqa: E402

BASE = "semeval_repo/task-dataset/semeval-2025-task11-dataset"
csv.field_size_limit(10**9)


def raw_counts(root: Path) -> dict[tuple[str, str, str], int]:
    """Row counts read with Python's csv, independent of Spark, as a parser cross-check."""
    out = {}
    for f in sorted(root.glob("track_*/*/*.csv")):
        if "_" in f.stem:
            continue
        with open(f, encoding="utf-8", newline="") as fh:
            out[(f.parts[-3], f.parts[-2], f.stem)] = sum(1 for _ in csv.DictReader(fh))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=None)
    args = ap.parse_args()
    cfg = load_config(args.config)
    root = Path(path_of(cfg, "raw", BASE))
    counts = raw_counts(root)
    silver = pd.read_parquet(path_of(cfg, "silver", "brighter"), columns=["id", "lang", "split", "track", "source", *EMOS, "neutral"])
    intensity = pd.read_parquet(path_of(cfg, "bronze", "intensity"), columns=["lang", "id"])
    mask = pd.read_parquet(path_of(cfg, "bronze", "label_mask")).set_index("lang")["mask"].to_dict()
    fam = families(cfg)
    tok = pd.read_csv(path_of(cfg, "reports", "token_lengths.csv")).set_index("lang")

    bad = []
    for (lang, split), n in silver.groupby(["lang", "split"]).size().items():
        track = "track_a" if silver[silver["lang"] == lang]["track"].iloc[0] == "A" else "track_c"
        if counts.get((track, split, lang)) != n:
            bad.append((lang, split, n, counts.get((track, split, lang))))

    n_int = intensity.groupby("lang").size().to_dict()
    has_i = silver.assign(key=silver["lang"] + "|" + silver["id"])
    i_keys = set(intensity["lang"] + "|" + intensity["id"])
    has_i["has_int"] = has_i["key"].isin(i_keys)

    L = ["# BRIGHTER data notes (M1)", "", "Generated by `scripts/make_data_notes.py`. Counts only; no BRIGHTER text.", "",
         "## Source", "",
         f"Source of truth: the SemEval repository, `data/raw/brighter/{BASE}/track_{{a,b,c}}/{{train,dev,test}}/<lang>.csv`.",
         "Columns: `id, text`, then one integer column per emotion the language has. Track B holds intensities 0 to 3.",
         "No official evaluation script is in the data repository. The scorer lives in the separate repository "
         "`SemEval2025-Task11-Evaluation`: sklearn macro-F1 for Tracks A and C, per-emotion Pearson r for Track B. "
         "`emoldgn/evaluate.py` reproduces it (see `tests/test_metrics.py`).",
         "Per-annotator files for optional N3 are in `semeval_repo/individual_labels/<lang>/` (12 languages: "
         "afr, arq, chn, deu, eng, esp, hin, mar, ptbr, ron, swe, ukr). The format varies by language; inspect it in M11.", "",
         "## Findings that changed the pipeline", "",
         "1. **English Track A test labels are blank.** Filled from SemEval Track C, whose labels equal Track A test for "
         "every other language and which matches all 2,765 English rows by text. Two texts duplicated in Track C with "
         "conflicting labels (6 rows) fall back to row-aligned Track B intensity > 0. Binarised Track B disagrees with "
         "Track C on 3 of 2,765 rows, so the choice barely matters.",
         "2. **Hugging Face was not needed and is not safe to join for English test.** Its `eng` test split has 5,528 rows "
         "(2,762 distinct) and only 188 texts match SemEval exactly. It was still downloaded, as CLAUDE.md section 3 asks.",
         "3. **`track_a/train/ron_track1_test.csv` is a stray file** (other schema, id prefix `ron_test_track1`, 116 texts "
         "shared with Romanian test). It is ignored; ingesting it would put test texts into training.",
         "4. **Intensities join on text, not id.** After prefix normalisation, Track A and B ids point at different texts "
         "for amh and rus (0 agree) and for part of English train (2,071 of 2,763 agree).",
         "5. **Track B's amh and rus splits differ from Track A's.** About 1,040 amh Track A train texts are in Track B test, "
         "and 178 rus Track A test texts are in Track B dev. Each row therefore keeps its Track A split, and Track B is "
         "scored on the Track A test part. Scoring official Track B amh/rus test would measure training data. Every Track B "
         "row has a Track A row, so nothing is lost; amh and rus Track B test row counts differ from the official files.",
         "6. **Track C files repeat Track A test under new ids** for the 28 Track A languages. Only ind, jav, xho and zul "
         "have no training data, so only these are ingested as Track C and scored as zero-shot.",
         "7. **Exact-duplicate texts cross official splits** in a few languages (test texts also in train or dev: ibo 72, "
         "swa 8, orm 6, tir 4, and 1 each in eng, esp, ptbr, swe). Official splits are kept as released.",
         "8. **afr has no surprise column** (the README notes only that some languages lack an emotion); English has no disgust. "
         "Masks come from each file's header.",
         "9. **The README's Track B Sundanese is absent** from the files: Track B has 11 languages (amh, arq, chn, deu, eng, "
         "esp, hau, ptbr, ron, rus, ukr), as in the task paper. Romanian has Track B dev and test only.", "",
         "## Counts", "",
         f"Row counts match an independent Python csv count for every language and split: **{'yes' if not bad else 'NO: ' + str(bad)}**.", "",
         "| Lang | Family | Track | Train | Dev | Test | Emotions present | Intensity rows | p95 tokens | Label source |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    table = silver.groupby(["lang", "split"]).size().unstack(fill_value=0)
    for lang in table.index:
        row = silver[silver["lang"] == lang]
        present = ",".join(e[:3] for e, m in zip(EMOS, mask[lang]) if m)
        srcs = "+".join(sorted(row["source"].unique()))
        L.append(f"| {lang} | {fam.get(lang, '?')} | {row['track'].iloc[0]} | {table.loc[lang].get('train', 0)} | "
                 f"{table.loc[lang].get('dev', 0)} | {table.loc[lang].get('test', 0)} | {present} | {n_int.get(lang, 0)} | "
                 f"{tok.loc[lang, 'p95']:.0f} | {srcs} |")
    a = silver[silver["track"] == "A"]
    L += ["", f"Track A total: {len(a[a['split'] == 'train']):,} train, {len(a[a['split'] == 'dev']):,} dev, "
          f"{len(a[a['split'] == 'test']):,} test. Track C zero-shot: "
          f"{len(silver[(silver['track'] == 'C') & (silver['split'] == 'test')]):,} test rows.", "",
          "Missing relative to the task README: nothing in Track A or C. Sundanese Track B is absent, as noted above.", "",
          "## Label prevalence, Track A train (share of rows)", "",
          "| Lang | " + " | ".join(e[:3] for e in EMOS) + " | neutral |", "|---|" + "---|" * 7]
    train = a[a["split"] == "train"]
    for lang, g in train.groupby("lang"):
        vals = [f"{g[e].mean():.3f}" if g[e].notna().any() else "-" for e in EMOS]
        L.append(f"| {lang} | " + " | ".join(vals) + f" | {g['neutral'].mean():.3f} |")
    sub = train[train["lang"].isin(cfg["subset_langs"])]
    per = sub.groupby("lang").size().to_dict()
    L += ["", "## Subset", "", f"`subset_langs` = {cfg['subset_langs']}: {len(sub):,} official train rows ({per}). "
          "All exist with at least 1,500 rows, and the total is inside the 8k to 12k target.", ""]
    meta = json.loads(Path(path_of(cfg, "gold", "tokenizer_meta.json")).read_text())
    L += ["## Token lengths", "", f"Chosen `max_len`: {meta['max_len']}. See `reports/token_lengths.csv`.", ""]
    Path(path_of(cfg, "reports", "DATA_NOTES.md")).write_text("\n".join(L), encoding="utf-8")
    print("mismatches:", bad)
    print("wrote reports/DATA_NOTES.md")


if __name__ == "__main__":
    main()
