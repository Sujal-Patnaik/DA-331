#!/usr/bin/env python
"""Checks that the apps' first tab shows our model's results on the test (demo) data; writes reports/app_provenance.md.

1. which run the exported model came from, and that its weights equal that run's best checkpoint;
2. that the stored documents are exactly the demo inputs, and the counts the app shows;
3. that no clause text matches BRIGHTER text (training data never leaks into the app tables);
4. that re-scoring a random sample of stored clauses with the exported model reproduces the stored
   probabilities, and that re-deriving labels, states and urgency reproduces the stored ones.
Prints counts only, never dataset text.
"""
from __future__ import annotations

import hashlib
import importlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from apps.engine.aspects import load_profile  # noqa: E402
from apps.engine.scorer import get_scorer  # noqa: E402
from spark_jobs.common import load_config, path_of  # noqa: E402

SAMPLE = 300


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 24), b""):
            h.update(block)
    return h.hexdigest()


def main() -> None:
    cfg = load_config()
    art = Path(path_of(cfg, "artifacts"))
    run = json.loads((art / "lang_index.json").read_text())["run"]
    same = sha(art / "best.pt") == sha(ROOT / "runs" / run / "ckpt_best.pt")
    L = ["# Provenance of the apps' test-data results", "", "Generated by scripts/check_app_provenance.py. Counts only.", "",
         "## Model", "", f"- Exported model comes from run `{run}`.", f"- Its weights are byte-identical to `runs/{run}/ckpt_best.pt`: **{same}**.",
         "- That model was trained on BRIGHTER only; neither demo dataset was used for training or tuning.", ""]

    brighter = set(pd.read_parquet(ROOT / "data/silver/brighter", columns=["text"])["text"].str.strip())
    brighter |= set(pd.read_parquet(ROOT / "data/silver/brighter", columns=["text_raw"])["text_raw"].str.strip())
    aggregate = importlib.import_module("spark_jobs.10_aggregate")
    scorer = get_scorer(art)
    for profile in ("customer_support", "student_feedback"):
        gold = ROOT / "apps/gold" / profile
        bronze = pd.read_parquet(ROOT / "apps/bronze" / profile / "documents", columns=["doc_id", "source"])
        docs = pd.read_parquet(gold / "documents", columns=["doc_id", "source", "escalate", "group_id"])
        cl = pd.read_parquet(gold / "clauses", columns=["doc_id", "clause_id", "clause", "lang", "probs", "inten", "present", "states", "urgency"])
        overlap = int(cl["clause"].str.strip().isin(brighter).sum())
        L += [f"## {profile}", "",
              f"- Demo input documents: {len(bronze):,} (sources: {', '.join(sorted(bronze['source'].unique()))})",
              f"- Documents shown in the app: {len(docs):,}; same ids as the input: **{set(docs['doc_id']) == set(bronze['doc_id'])}**",
              f"- Clauses shown: {len(cl):,}; groups: {docs['group_id'].nunique():,}; escalated: {int(docs['escalate'].sum()):,}",
              f"- Clauses whose text exactly matches a BRIGHTER text: {overlap:,} of {len(cl):,}"]

        s = cl.sample(SAMPLE, random_state=7).reset_index(drop=True)
        r = scorer.score(s["clause"].tolist(), s["lang"].tolist())
        stored_p = np.stack(s["probs"].values)
        diff = np.abs(np.asarray(r["probs"]) - stored_p)
        s2 = s.assign(probs=list(r["probs"]), inten=list(r["inten"]))
        prof = load_profile(ROOT / "profiles" / f"{profile}.yaml")
        d = aggregate.derive_clause(cfg, prof, s2[["clause", "lang", "probs", "inten"]])
        same_present = float((np.stack(d["present"].values) == np.stack(s["present"].values)).all(1).mean())
        same_states = float(np.mean([sorted(a) == sorted(b) for a, b in zip(d["states"], s["states"])]))
        u_diff = float(np.abs(d["urgency"].values - s["urgency"].values).max())
        L += [f"- Fresh re-scoring of {SAMPLE} random stored clauses: max probability difference {diff.max():.4f}, mean {diff.mean():.5f}",
              f"- Same emotion labels after re-deriving: {same_present:.1%}; same states: {same_states:.1%}; max urgency difference {u_diff:.4f}", ""]
    out = ROOT / "reports/app_provenance.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
